"""Stage 9: reproducibility check.

Runs the generator three times as separate processes (so per-process hash
randomisation cannot hide nondeterminism): twice with the same seed into two folders
and once with a different seed. It compares row counts and the SHA-256 checksums of
every output file, and writes the evidence to a markdown report.

Usage: python -m generator.reproducibility [--profile full] [--seed N] [--other-seed M]
                                           [--work DIR] [--report FILE]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import subprocess
import sys
from pathlib import Path

from . import __version__
from .config import DEFAULT_SEED

PROJECT_ROOT = Path(__file__).resolve().parents[1]


def _generate(profile: str, seed: int, out: Path) -> list[str]:
    command = [sys.executable, "-m", "generator", "--profile", profile, "--seed", str(seed), "--out", str(out)]
    subprocess.run(command, cwd=PROJECT_ROOT, check=True, capture_output=True, text=True)
    return ["python", "-m", "generator", "--profile", profile, "--seed", str(seed), "--out", out.as_posix()]


def _checksums(folder: Path) -> dict[str, str]:
    pairs = (line.split("  ", 1) for line in (folder / "checksums.sha256").read_text(encoding="utf-8").splitlines())
    return {rel: digest for digest, rel in pairs}


def _row_counts(folder: Path) -> dict[str, int]:
    return json.loads((folder / "source_manifest.json").read_text(encoding="utf-8"))["row_counts"]


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check(profile: str, seed: int, other_seed: int, work: Path) -> dict:
    """Generate runs A, B (same seed) and C (other seed); return the comparison."""
    runs = {"A": (seed, work / "run_a"), "B": (seed, work / "run_b"), "C": (other_seed, work / "run_c")}
    commands = {name: _generate(profile, s, out) for name, (s, out) in runs.items()}
    sums = {name: _checksums(out) for name, (_, out) in runs.items()}
    counts = {name: _row_counts(out) for name, (_, out) in runs.items()}
    # A file is listed in its own run's checksums; recompute to prove the lists are truthful.
    for name, (_, out) in runs.items():
        for rel, digest in sums[name].items():
            if _digest(out / rel) != digest:
                raise RuntimeError(f"run {name}: checksum of {rel} does not verify")
    differing_c = sorted(rel for rel in sums["A"] if sums["C"].get(rel) != sums["A"][rel])
    return {
        "profile": profile, "seed": seed, "other_seed": other_seed, "commands": commands,
        "row_counts": counts, "checksums": sums,
        "checksum_list_digest": {name: _digest(out / "checksums.sha256") for name, (_, out) in runs.items()},
        "same_seed_identical": sums["A"] == sums["B"] and counts["A"] == counts["B"],
        "same_seed_differing_files": sorted(rel for rel in sums["A"] if sums["B"].get(rel) != sums["A"][rel]),
        "other_seed_differing_files": differing_c,
        "other_seed_identical_files": sorted(set(sums["A"]) - set(differing_c)),
    }


def report(result: dict) -> str:
    """Render the comparison as markdown."""
    a, b, c = (result["row_counts"][k] for k in "ABC")
    lines = [
        "# Reproducibility", "",
        f"Generated by `python -m generator.reproducibility --profile {result['profile']} --seed {result['seed']} "
        f"--other-seed {result['other_seed']}` (generator {__version__}, Python {platform.python_version()}).",
        "Each run is a separate process; every output file is compared by SHA-256.", "",
        "## Verdict", "",
        f"* Same seed ({result['seed']}), runs A and B: **{'IDENTICAL' if result['same_seed_identical'] else 'DIFFERENT'}** "
        f"- {len(result['checksums']['A']) - len(result['same_seed_differing_files'])} of {len(result['checksums']['A'])} "
        "files byte-identical, row counts equal.",
        f"* Different seed ({result['other_seed']}), run C: **{len(result['other_seed_differing_files'])} of "
        f"{len(result['checksums']['A'])} files differ**; the "
        f"{len(result['other_seed_identical_files'])} identical files are seed-independent "
        f"({', '.join(result['other_seed_identical_files'])}).",
        "", "Digest of each run's `checksums.sha256`:", "", "| run | seed | sha256(checksums.sha256) |", "|---|---|---|",
    ]
    seeds = {"A": result["seed"], "B": result["seed"], "C": result["other_seed"]}
    lines += [f"| {k} | {seeds[k]} | `{result['checksum_list_digest'][k]}` |" for k in "ABC"]
    lines += ["", "## Commands", "", "```bash"] + [" ".join(result["commands"][k]) for k in "ABC"] + ["```", "",
              "## Row counts", "", "| table | run A | run B | run C |", "|---|---|---|---|"]
    lines += [f"| {t} | {a[t]} | {b[t]} | {c[t]} |" for t in a]
    lines += ["", "## Checksums (run A vs B vs C)", "", "| file | run A = run B | run C differs |", "|---|---|---|"]
    for rel, digest in result["checksums"]["A"].items():
        same = "yes" if result["checksums"]["B"].get(rel) == digest else "**NO**"
        other = "yes" if rel in result["other_seed_differing_files"] else "no"
        lines.append(f"| {rel} `{digest[:16]}...` | {same} | {other} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m generator.reproducibility", description=__doc__.split("\n")[0])
    parser.add_argument("--profile", choices=["full", "starter"], default="full")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--other-seed", type=int, default=DEFAULT_SEED + 1)
    parser.add_argument("--work", type=Path, default=Path("output") / "reproducibility")
    parser.add_argument("--report", type=Path, default=Path("docs") / "reproducibility.md")
    args = parser.parse_args(argv)
    result = check(args.profile, args.seed, args.other_seed, args.work)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(report(result), encoding="utf-8", newline="\n")
    print(f"same seed identical: {result['same_seed_identical']} "
          f"({len(result['checksums']['A']) - len(result['same_seed_differing_files'])}/{len(result['checksums']['A'])} files)")
    print(f"different seed: {len(result['other_seed_differing_files'])}/{len(result['checksums']['A'])} files differ")
    for k in "ABC":
        print(f"run {k}: sha256(checksums.sha256) = {result['checksum_list_digest'][k]}")
    print(f"report: {args.report.as_posix()}")
    return 0 if result["same_seed_identical"] and result["other_seed_differing_files"] else 1


if __name__ == "__main__":
    sys.exit(main())
